#!/usr/bin/env node
/**
 * gen-emotion-ball-data.mjs —— 把 aora-bot/emotion-ball 的几何与表情数据转成 C#。
 *
 * 数据源(只读,不修改): D:/Project/aora-bot/emotion-ball/js/{rings,emotions}.js
 * 产物(生成,勿手改):   ../src/DesktopHub.App/EmotionBall/{EmotionBallData,EmotionSeed}.cs
 *
 * 用法: node tools/gen-emotion-ball-data.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = 'D:/Project/aora-bot/emotion-ball/js';
const OUT_DIR = path.resolve(here, '../src/DesktopHub.App/EmotionBall');

// 在伪 window 上执行原始数据文件,得到纯数据对象
const window = {};
new Function('window', fs.readFileSync(path.join(SRC, 'rings.js'), 'utf8'))(window);
new Function('window', fs.readFileSync(path.join(SRC, 'emotions.js'), 'utf8'))(window);
const RD = window.EB_RINGS;
const SEED = window.EMOTION_SEED;
if (!RD || !SEED) throw new Error('数据文件加载失败');

const HEADER = (name) => `// <auto-generated>
// 由 tools/gen-emotion-ball-data.mjs 自动生成,数据源自 aora-bot/emotion-ball(社区许可,出处见 README)。
// 勿手改;数据更新时重新运行: node tools/gen-emotion-ball-data.mjs
// </auto-generated>
#nullable enable
namespace DesktopHub.App.EmotionBall;

`;

const num = (v) => {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error('非有限数: ' + v);
  return String(v);
};

/** 把数字数组折行成带缩进的初始化文本(每行 perLine 个) */
function wrapNums(arr, perLine, indent) {
  const lines = [];
  for (let i = 0; i < arr.length; i += perLine) {
    const chunk = arr.slice(i, i + perLine).map(num).join(', ');
    const tail = i + perLine < arr.length ? ',' : ',';
    lines.push(indent + chunk + tail);
  }
  return lines.join('\n');
}

// ---------------- EmotionBallData.cs ----------------

const RINGS = RD.EXPRESSIONS; // 25 组 × [左眼, 右眼] × 48 点
const BODY = RD.SHAPES.blob;

const ringLines = [];
RINGS.forEach((pair, i) => {
  pair.forEach((ring, e) => {
    const flat = [];
    for (const [x, y] of ring) flat.push(x, y);
    ringLines.push(`        // 环 ${i} ${e === 0 ? '左' : '右'}`);
    ringLines.push(wrapNums(flat, 6, '        '));
  });
});

const bodyLines = [];
{
  const flat = [];
  for (const [x, y] of BODY.ring) flat.push(x, y);
  bodyLines.push(wrapNums(flat, 6, '        '));
}

const dataCs = `${HEADER('EmotionBallData')}/// <summary>
/// 表情球几何数据(与原版坐标系一致:viewBox -15 -15 259 259,头部中心 ${RD.HEAD_C})。
/// 扁平存储:眼环 idx = ((环*2 + 眼) * 48 + 点) * 2 + xy;身体 idx = 点 * 2 + xy。
/// </summary>
public static class EmotionBallData
{
    public const double HeadC = ${num(RD.HEAD_C)};
    public const double EyeHalf = ${num(RD.EYE_HALF)};
    public const int RingCount = ${RINGS.length};
    public const int EyePoints = ${RINGS[0][0].length};
    public const int BodyPoints = ${BODY.ring.length};

    /// <summary>blob 脸部拟合参数(眼睛贴合身体轮廓的缩放/偏移)。</summary>
    public const double FaceX = ${num(BODY.face.x)}, FaceY = ${num(BODY.face.y)},
        FaceSx = ${num(BODY.face.sx)}, FaceSy = ${num(BODY.face.sy)}, FaceEye = ${num(BODY.face.eye)};

    /// <summary>25 组表情眼环(48 点闭合轮廓)。</summary>
    public static readonly double[] Rings =
    [
${ringLines.join('\n')}
    ];

    /// <summary>blob 身体轮廓环(96 点闭合)。</summary>
    public static readonly double[] BodyRing =
    [
${bodyLines.join('\n')}
    ];
}
`;

// ---------------- EmotionSeed.cs ----------------

const BODY_KEYS = { x: 'X', y: 'Y', scale: 'Scale', rotate: 'Rotate', breathe: 'Breathe', zzz: 'Zzz', orbit: 'Orbit', ribbons: 'Ribbons', confetti: 'Confetti' };
const EYE_KEYS = { x: 'X', y: 'Y', scaleX: 'ScaleX', scaleY: 'ScaleY', rotate: 'Rotate', open: 'Open', lookX: 'LookX', lookY: 'LookY' };
const ANIM_KEYS = { amp: 'Amp', period: 'Period', phase: 'Phase', phaseMs: 'PhaseMs', speed: 'Speed', decay: 'Decay', interval: 'Interval', dur: 'Dur', depth: 'Depth' };

function emitBody(b) {
  const p = [];
  for (const [k, cs] of Object.entries(BODY_KEYS)) if (b[k] !== undefined) p.push(`${cs}=${num(b[k])}`);
  if (b.color !== undefined) p.push(`Color="${b.color}"`);
  return p.length ? `new BodySpec { ${p.join(', ')} }` : 'null';
}

function emitEye(e) {
  const p = [];
  for (const [k, cs] of Object.entries(EYE_KEYS)) if (e[k] !== undefined) p.push(`${cs}=${num(e[k])}`);
  if (e.color !== undefined) p.push(`Color="${e.color}"`);
  return p.length ? `new EyeSpec { ${p.join(', ')} }` : 'null';
}

function emitAnim(a) {
  const p = [`Target="${a.target}"`, `Prop="${a.prop}"`, `Type="${a.type}"`];
  for (const [k, cs] of Object.entries(ANIM_KEYS)) if (a[k] !== undefined) p.push(`${cs}=${num(a[k])}`);
  return `new AnimRaw { ${p.join(', ')} }`;
}

function emitFrame(f) {
  const p = [`At=${num(f.at || 0)}`];
  if (f.body) p.push(`Body=${emitBody(f.body)}`);
  if (f.eyes) {
    if (f.eyes.both) p.push(`Both=${emitEye(f.eyes.both)}`);
    if (f.eyes.left) p.push(`Left=${emitEye(f.eyes.left)}`);
    if (f.eyes.right) p.push(`Right=${emitEye(f.eyes.right)}`);
  }
  return `new SeqFrameRaw { ${p.join(', ')} }`;
}

function emitEmotion(e) {
  const p = [];
  p.push(`Id="${e.id}"`, `Name="${e.name}"`, `Group="${e.group}"`);
  if (e.desc) p.push(`Desc="${e.desc.replace(/"/g, '\\"')}"`);
  if (e.transition !== undefined) p.push(`Transition=${num(e.transition)}`);
  if (e.gaze === false) p.push(`Gaze=false`);
  if (e.pool) p.push(`Pool=new int[]{ ${e.pool.join(', ')} }`);
  if (e.poolMs) p.push(`PoolMs=new double[]{ ${e.poolMs.map(num).join(', ')} }`);
  if (e.poolSpeed !== undefined) p.push(`PoolSpeed=${num(e.poolSpeed)}`);
  if (e.blinkMs === null) p.push(`BlinkOff=true`);
  else if (e.blinkMs) p.push(`BlinkMs=new double[]{ ${e.blinkMs.map(num).join(', ')} }`);
  if (e.openness !== undefined) p.push(`Openness=${num(e.openness)}`);
  if (e.antics) p.push(`Antics=true`);
  if (e.body) p.push(`Body=${emitBody(e.body)}`);
  if (e.eyes) {
    if (e.eyes.both) p.push(`Both=${emitEye(e.eyes.both)}`);
    if (e.eyes.left) p.push(`Left=${emitEye(e.eyes.left)}`);
    if (e.eyes.right) p.push(`Right=${emitEye(e.eyes.right)}`);
  }
  if (e.anims) p.push(`Anims=new AnimRaw[]{ ${e.anims.map(emitAnim).join(', ')} }`);
  if (e.sequence) {
    const s = e.sequence;
    if (typeof s.settle === 'string') p.push(`Settle="${s.settle}"`);
    else if (s.settle && s.settle.next) p.push(`SettleNext="${s.settle.next}"`);
    if (s.frames) p.push(`Frames=new SeqFrameRaw[]{ ${s.frames.map(emitFrame).join(', ')} }`);
  }
  return `        new EmotionRaw { ${p.join(', ')} },`;
}

const seedCs = `${HEADER('EmotionSeed')}/// <summary>
/// 32 个表情种子定义,与 aora-bot emotions.js 一一对应(勿手改)。
/// 字段语义见原文件头注释:pool 眼环池 / blinkMs 眨眼间隔 / sequence 关键帧序列等。
/// </summary>
public static class EmotionSeed
{
    public static List<EmotionRaw> Create() =>
    [
${SEED.map(emitEmotion).join('\n')}
    ];
}
`;

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, 'EmotionBallData.cs'), dataCs);
fs.writeFileSync(path.join(OUT_DIR, 'EmotionSeed.cs'), seedCs);
console.log(`已生成: EmotionBallData.cs(${(dataCs.length / 1024).toFixed(1)} KB) / EmotionSeed.cs(${(seedCs.length / 1024).toFixed(1)} KB),表情 ${SEED.length} 个,眼环 ${RINGS.length} 组`);
